"""Freeze Python3.12 Unicode15 full casefold for portable archive-name parity."""
import hashlib
import json
import unicodedata
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]

def main():
    assert unicodedata.unidata_version=="15.0.0"
    mappings={str(i):chr(i).casefold() for i in range(0x110000) if chr(i).casefold()!=chr(i)}
    target=ROOT/"product/config/portable-names.json"; assert not target.exists()
    target.write_text(json.dumps(dict(unicode_version=unicodedata.unidata_version,mappings=mappings),ensure_ascii=True,separators=(",",":"))+"\n",encoding="utf-8")
    code=ROOT/"product/android/core-model/src/main/java/org/packrag/model/PortableNames.kt"; assert not code.exists()
    def literal(value):
        units=value.encode("utf-16-be")
        return '"'+''.join('\\u'+units[i:i+2].hex() for i in range(0,len(units),2))+'"'
    records=list(mappings.items()); pieces=[records[i:i+128] for i in range(0,len(records),128)]
    parts=['package org.packrag.model','', '// Generated by scripts/v13_portable_names.py; do not hand-edit mappings.', 'object PortableNames {', '    const val UNICODE_VERSION = "15.0.0"', '    private val mappings: Map<Int,String> = buildMap {']
    for i in range(len(pieces)): parts.append(f'        putAll(part{i}())')
    parts += ['    }','    fun fold(text: String): String = buildString { text.codePoints().forEach { point -> mappings[point]?.let { append(it) } ?: appendCodePoint(point) } }',
        '    val order: Comparator<String> = Comparator { a,b -> compareCodepoints(a,b) }',
        '    private fun compareCodepoints(a:String,b:String):Int {',
        '        var i=0; var j=0',
        '        while(i<a.length && j<b.length) { val x=a.codePointAt(i); val y=b.codePointAt(j); if(x!=y) return x.compareTo(y); i+=Character.charCount(x); j+=Character.charCount(y) }',
        '        return (a.length-i).compareTo(b.length-j)', '    }']
    for i,piece in enumerate(pieces):
        parts.append(f'    private fun part{i}():Map<Int,String> = mapOf(')
        parts += [f'        {key} to {literal(value)}'+(',' if j<len(piece)-1 else '') for j,(key,value) in enumerate(piece)]
        parts.append('    )')
    parts.append('}')
    code.write_text('\n'.join(parts)+'\n',encoding='utf-8')
    print('Casefold entries:',len(mappings),'table SHA256:',hashlib.sha256(target.read_bytes()).hexdigest())

if __name__=="__main__": main()
