"""Generate portable Unicode 15 query tables; raw official inputs remain immutable.

The pinned Python 3.12 Unicode engine supplies fully expanded decompositions and
composition exclusions. Official UnicodeData/properties and normalization tests
are independently checked by the acceptance tests, rather than trusting this
generator as its own oracle. Archive-name folding is a separate contract.
"""
import argparse
import hashlib
import json
import unicodedata as ud
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def ranges(values):
    result = []
    for point in sorted(values):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def generate(inputs):
    assert ud.unidata_version == "15.0.0", ud.unidata_version
    acquisition = json.loads((inputs / "acquisition.json").read_text())
    for name, record in acquisition["files"].items():
        assert hashlib.sha256((inputs / name).read_bytes()).hexdigest() == record["sha256"]
    properties = {"Cased": set(), "Case_Ignorable": set()}
    for line in (inputs / "DerivedCoreProperties.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        interval, prop = map(str.strip, line.split(";"))
        if prop in properties:
            ends = interval.split("..")
            properties[prop].update(range(int(ends[0], 16), int(ends[-1], 16) + 1))
    decomposition, combining, lower, composition, word, whitespace = {}, {}, {}, {}, set(), set()
    for point in range(0x110000):
        if 0xD800 <= point <= 0xDFFF:
            continue
        char = chr(point)
        expanded = ud.normalize("NFKD", char)
        if expanded != char and not 0xAC00 <= point <= 0xD7A3:
            decomposition[str(point)] = expanded
        ccc = ud.combining(char)
        if ccc:
            combining[str(point)] = ccc
        if char.lower() != char:
            lower[str(point)] = char.lower()
        raw = ud.decomposition(char).split()
        if len(raw) == 2 and not raw[0].startswith("<"):
            pair = ''.join(chr(int(x, 16)) for x in raw)
            if ud.normalize("NFC", pair) == char:
                composition[str((ord(pair[0]) << 21) | ord(pair[1]))] = point
        if ud.category(char)[0] in "LN" or char == "_":
            word.add(point)
        if char.isspace():
            whitespace.add(point)
    data = dict(unicode_version="15.0.0", decomposition=decomposition, combining=combining,
                lower=lower, composition=composition, word=ranges(word), whitespace=ranges(whitespace),
                cased=ranges(properties["Cased"]), case_ignorable=ranges(properties["Case_Ignorable"]),
                input_sha256={name: record["sha256"] for name, record in acquisition["files"].items()})
    raw = (json.dumps(data, ensure_ascii=True, separators=(",", ":")) + "\n").encode()
    parts = ['package org.packrag.model', '', '// Generated by scripts/v13_query_unicode.py; do not hand-edit.',
             'internal object QueryUnicodeData {', '    const val VERSION = "15.0.0"',
             f'    const val TABLE_SHA256 = "{hashlib.sha256(raw).hexdigest()}"']
    def literal(text):
        units = text.encode("utf-16-be")
        return '"' + ''.join('\\u' + units[i:i+2].hex() for i in range(0, len(units), 2)) + '"'
    for name in ("decomposition", "combining", "lower", "composition"):
        records = list(data[name].items())
        pieces = [records[i:i+128] for i in range(0, len(records), 128)]
        key_type = "Long" if name == "composition" else "Int"
        value_type = "String" if name in ("decomposition", "lower") else "Int"
        parts.append(f'    val {name}: Map<{key_type},{value_type}> = buildMap {{')
        parts.extend(f'        putAll({name}{i}())' for i in range(len(pieces)))
        parts.append('    }')
        for i, piece in enumerate(pieces):
            parts.append(f'    private fun {name}{i}():Map<{key_type},{value_type}> = mapOf(')
            for j, (key, value) in enumerate(piece):
                rendered = literal(value) if value_type == "String" else str(value)
                parts.append(f'        {key}{"L" if key_type == "Long" else ""} to {rendered}' + (',' if j + 1 < len(piece) else ''))
            parts.append('    )')
    for name in ("word", "whitespace", "cased", "case_ignorable"):
        flat = ','.join(str(x) for pair in data[name] for x in pair)
        parts.append(f'    val {name} = intArrayOf({flat})')
    parts.append('}')
    return raw, ('\n'.join(parts) + '\n').encode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--inputs", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    targets = [ROOT / "product/config/query-unicode15.json",
               ROOT / "product/android/core-model/src/main/java/org/packrag/model/QueryUnicodeData.kt"]
    for target, raw in zip(targets, generate(args.inputs)):
        if args.check:
            assert target.read_bytes() == raw, target
        else:
            assert not target.exists(), target
            target.write_bytes(raw)
        print(target.relative_to(ROOT), len(raw), hashlib.sha256(raw).hexdigest())


if __name__ == "__main__":
    main()
